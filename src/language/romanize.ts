const nukta: Record<string, string> = { क: 'q', ख: 'kh', ग: 'g', ज: 'z', ड: 'r', ढ: 'rh', फ: 'f', य: 'y' };
const lookup = new Map(Object.entries(common).map(([k, v]) => [k.normalize('NFD'), v]));

function phonetic(word: string) {
  const chars = Array.from(word.normalize('NFD'));
  const units: { c: string; v: string; implicit: boolean }[] = [];
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    if (consonants[ch]) {
      let c = consonants[ch];
      if (chars[i + 1] === '़') {
        c = nukta[ch] || c;
        i++;
      }
      let v = 'a';
      let implicit = true;
      if (matras[chars[i + 1]]) {
        v = matras[chars[++i]];
        implicit = false;
      } else if (chars[i + 1] === '्') {
        v = '';
        implicit = false;
        i++;
      }
      units.push({ c, v, implicit });
    } else if (vowels[ch]) units.push({ c: '', v: vowels[ch], implicit: false });
    else if (ch === 'ं' || ch === 'ँ')
      units.push({ c: /[पफबभम]/u.test(chars[i + 1] || '') ? 'm' : 'n', v: '', implicit: false });
    else if (ch === 'ः') units.push({ c: 'h', v: '', implicit: false });
    else if (/[०-९]/u.test(ch)) units.push({ c: String(ch.charCodeAt(0) - 0x0966), v: '', implicit: false });
    else if (!/[\u0900-\u097f\u200c\u200d]/u.test(ch)) units.push({ c: ch, v: '', implicit: false });
  }
  // Hindi final-schwa deletion. Interior schwa deletion is conservative; a lexicon supplies
  // irregular/familiar spellings rather than silently pretending a phonetic fallback is perfect.
  if (units.length > 1 && units.at(-1)!.implicit) units.at(-1)!.v = '';
  for (let i = units.length - 2; i > 0; i--) {
    if (units[i].implicit && units[i + 1]?.c && units[i + 1]?.v && units[i - 1]?.v) units[i].v = '';
  }
  return units.map((u) => u.c + u.v).join('');
}

export function toHinglish(text: string): string {
  return text.normalize('NFC').replace(/[\u0900-\u097f]+/gu, (run) => {
    return run
      .split(/([।॥])/u)
      .map((part) =>
        part === '।' || part === '॥' ? '.' : (lookup.get(part.normalize('NFD')) ?? phonetic(part)),
      )
      .join('');
  });
}
